#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);
const registryPath = path.join(
  repositoryRoot,
  "configs/visual-scene/capability-registry.json"
);
const schemaPath = path.join(
  repositoryRoot,
  "configs/visual-scene/scene-plan.schema.json"
);
const assetSchemaPath = path.join(
  repositoryRoot,
  "configs/visual-scene/asset-manifest.schema.json"
);
const outputPaths = [
  "services/instruction-engine/src/visual-scene/scenePlan.generated.ts",
  "services/api-gateway/src/types/scenePlan.generated.ts",
  "apps/web-viewer/src/visual-scene/scenePlan.generated.ts",
  "apps/mobile-app/types/scenePlan.generated.ts",
].map((relativePath) => path.join(repositoryRoot, relativePath));
const checkOnly = process.argv.includes("--check");

function asConst(name, values) {
  return `export const ${name} = ${JSON.stringify(values, null, 2)} as const;\n`;
}

function render(registry) {
  const constraints = registry.constraints;
  return `// Generated by scripts/visual-scene/generate-contract-types.mjs.
// Source: configs/visual-scene/capability-registry.json. Do not edit by hand.

export const SCENE_PLAN_SCHEMA_VERSION = ${JSON.stringify(
    registry.schema_version
  )} as const;
export const CAPABILITY_REGISTRY_VERSION = ${JSON.stringify(
    registry.registry_version
  )} as const;

${asConst("SCENE_ACTIONS", registry.actions)}
${asConst("SCENE_TOPICS", registry.topics)}
${asConst("SCENE_ASSETS", registry.assets)}
${asConst("SEMANTIC_TARGETS", registry.targets)}
${asConst("ANIMATION_CLIPS", registry.clips)}
${asConst("ANIMATION_MORPHS", registry.morphs)}
${asConst("FLOW_PATHS", registry.paths)}
${asConst("SEMANTIC_STATES", registry.states)}
${asConst("LABEL_TEXT_KEYS", registry.text_keys)}
${asConst("SCENE_VIEW_MODES", registry.view_modes)}
export const SCENE_LIMITS = ${JSON.stringify(
    {
      max_required_assets: constraints.max_required_assets,
      max_tracks: constraints.max_tracks,
      max_steps: constraints.max_steps,
      max_evidence_refs: constraints.max_evidence_refs,
    },
    null,
    2
  )} as const;
export const TARGET_ASSETS = ${JSON.stringify(
    constraints.target_assets,
    null,
    2
  )} as const;
export const CLIP_TARGETS = ${JSON.stringify(
    constraints.clip_targets,
    null,
    2
  )} as const;
export const MORPH_TARGETS = ${JSON.stringify(
    constraints.morph_targets,
    null,
    2
  )} as const;
export const FLOW_PATH_REQUIREMENTS = ${JSON.stringify(
    constraints.flow_paths,
    null,
    2
  )} as const;
${asConst("CAMERA_TARGETS", constraints.camera_targets)}
${asConst("MATERIAL_TARGETS", constraints.material_targets)}
export const CONFLICT_GROUPS = ${JSON.stringify(
    constraints.conflict_groups,
    null,
    2
  )} as const;

export type SceneAction = (typeof SCENE_ACTIONS)[number];
export type SceneTopic = (typeof SCENE_TOPICS)[number];
export type SceneAssetId = (typeof SCENE_ASSETS)[number];
export type SemanticTarget = (typeof SEMANTIC_TARGETS)[number];
export type AnimationClip = (typeof ANIMATION_CLIPS)[number];
export type AnimationMorph = (typeof ANIMATION_MORPHS)[number];
export type FlowPath = (typeof FLOW_PATHS)[number];
export type SemanticState = (typeof SEMANTIC_STATES)[number];
export type LabelTextKey = (typeof LABEL_TEXT_KEYS)[number];
export type SceneViewMode = (typeof SCENE_VIEW_MODES)[number];
export type CameraTarget = (typeof CAMERA_TARGETS)[number];
export type MaterialTarget = (typeof MATERIAL_TARGETS)[number];

type TrackBase<
  TAction extends SceneAction,
  TTarget extends SemanticTarget = SemanticTarget
> = {
  id: string;
  target: TTarget;
  action: TAction;
  start_ms: number;
  duration_ms: number;
};

export type PlayClipTrack = {
  [TClip in AnimationClip]: TrackBase<
    "play_clip",
    (typeof CLIP_TARGETS)[TClip][number]
  > & {
    clip: TClip;
    loop: boolean;
  };
}[AnimationClip];

export type PlayMorphTrack = {
  [TMorph in AnimationMorph]: TrackBase<
    "play_morph",
    (typeof MORPH_TARGETS)[TMorph][number]
  > & {
    morph: TMorph;
    from: number;
    to: number;
  };
}[AnimationMorph];

export type FlowTrack = {
  [TPath in FlowPath]: TrackBase<
    "particle_flow" | "signal_propagation",
    (typeof FLOW_PATH_REQUIREMENTS)[TPath]["target"]
  > & {
    path: TPath;
    state: (typeof FLOW_PATH_REQUIREMENTS)[TPath]["state"];
  };
}[FlowPath];

export type MaterialTrack = TrackBase<
  "highlight" | "set_material_state",
  MaterialTarget
> & {
  state: SemanticState;
};

export type FadeTrack = TrackBase<"fade", MaterialTarget> & {
  opacity: number;
};

export type LabelTrack = {
  [TTextKey in LabelTextKey]: TrackBase<"show_label", TTextKey> & {
    text_key: TTextKey;
  };
}[LabelTextKey];

export type CameraTrack = TrackBase<
  "camera_focus" | "camera_orbit",
  CameraTarget
>;
export type WaitTrack = TrackBase<"wait">;

export type SceneTrack =
  | PlayClipTrack
  | PlayMorphTrack
  | FlowTrack
  | MaterialTrack
  | FadeTrack
  | LabelTrack
  | CameraTrack
  | WaitTrack;

export type SceneStep = {
  id: string;
  start_ms: number;
  end_ms: number;
  caption: string;
};

export type SceneFallback = {
  view_mode: SceneViewMode;
  message: string;
};

export type ScenePlan = {
  schema_version: typeof SCENE_PLAN_SCHEMA_VERSION;
  capability_registry_version: typeof CAPABILITY_REGISTRY_VERSION;
  plan_id: string;
  topic: SceneTopic;
  learning_objective: string;
  duration_ms: number;
  loop: boolean;
  required_assets: SceneAssetId[];
  tracks: SceneTrack[];
  steps: SceneStep[];
  evidence_refs: string[];
  fallback: SceneFallback;
};
`;
}

function assertSameValues(label, schemaValues, registryValues) {
  if (
    !Array.isArray(schemaValues) ||
    JSON.stringify(schemaValues) !== JSON.stringify(registryValues)
  ) {
    throw new Error(`${label} does not match the capability registry`);
  }
}

function orderedMappedTargets(registryTargets, mappingValues) {
  const mappedTargets = new Set(mappingValues.flat());
  return registryTargets.filter((target) => mappedTargets.has(target));
}

async function main() {
  const registry = JSON.parse(await readFile(registryPath, "utf8"));
  const schema = JSON.parse(await readFile(schemaPath, "utf8"));
  const assetSchema = JSON.parse(await readFile(assetSchemaPath, "utf8"));

  if (schema.properties.schema_version.const !== registry.schema_version) {
    throw new Error("Scene schema version does not match the capability registry");
  }
  if (
    schema.properties.capability_registry_version.const !== registry.registry_version
  ) {
    throw new Error(
      "Scene schema capability version does not match the capability registry"
    );
  }
  assertSameValues("Scene topics", schema.properties.topic.enum, registry.topics);
  assertSameValues(
    "Scene assets",
    schema.properties.required_assets.items.enum,
    registry.assets
  );
  assertSameValues("Scene targets", schema.$defs.target.enum, registry.targets);
  assertSameValues(
    "Scene actions",
    schema.$defs.trackBase.properties.action.enum,
    registry.actions
  );
  assertSameValues(
    "Scene clips",
    schema.$defs.track.oneOf[0].allOf[1].properties.clip.enum,
    registry.clips
  );
  assertSameValues(
    "Scene morphs",
    schema.$defs.track.oneOf[1].allOf[1].properties.morph.enum,
    registry.morphs
  );
  assertSameValues(
    "Scene flow paths",
    schema.$defs.track.oneOf[2].allOf[1].properties.path.enum,
    registry.paths
  );
  assertSameValues(
    "Scene material states",
    schema.$defs.track.oneOf[3].allOf[1].properties.state.enum,
    registry.states
  );
  const constraints = registry.constraints;
  if (
    schema.$defs.track.oneOf[0].allOf[1].properties.target.const !==
    constraints.clip_targets[registry.clips[0]][0]
  ) {
    throw new Error("Scene clip targets do not match the capability registry");
  }
  assertSameValues(
    "Scene morph targets",
    schema.$defs.track.oneOf[1].allOf[1].properties.target.enum,
    orderedMappedTargets(
      registry.targets,
      Object.values(constraints.morph_targets)
    )
  );
  assertSameValues(
    "Scene flow targets",
    schema.$defs.track.oneOf[2].allOf[1].properties.target.enum,
    orderedMappedTargets(
      registry.targets,
      Object.values(constraints.flow_paths).map((requirement) => [
        requirement.target,
      ])
    )
  );
  assertSameValues(
    "Scene material targets",
    schema.$defs.track.oneOf[3].allOf[1].properties.target.enum,
    constraints.material_targets
  );
  assertSameValues(
    "Scene fade targets",
    schema.$defs.track.oneOf[4].allOf[1].properties.target.enum,
    constraints.material_targets
  );
  assertSameValues(
    "Scene label targets",
    schema.$defs.track.oneOf[5].allOf[1].properties.target.enum,
    registry.text_keys
  );
  assertSameValues(
    "Scene camera targets",
    schema.$defs.track.oneOf[6].allOf[1].properties.target.enum,
    constraints.camera_targets
  );
  const morphRelations = Object.fromEntries(
    schema.$defs.track.oneOf[1].allOf[1].oneOf.map((relation) => [
      relation.properties.morph.const,
      relation.properties.target.enum,
    ])
  );
  if (
    JSON.stringify(morphRelations) !==
    JSON.stringify(constraints.morph_targets)
  ) {
    throw new Error("Scene morph relationships do not match the capability registry");
  }
  const flowRelations = Object.fromEntries(
    schema.$defs.track.oneOf[2].allOf[1].oneOf.map((relation) => [
      relation.properties.path.const,
      {
        target: relation.properties.target.const,
        state: relation.properties.state.const,
      },
    ])
  );
  for (const [pathName, relation] of Object.entries(flowRelations)) {
    const expected = constraints.flow_paths[pathName];
    if (
      !expected ||
      relation.target !== expected.target ||
      relation.state !== expected.state
    ) {
      throw new Error(`Scene flow relationship drifted for ${pathName}`);
    }
  }
  const labelRelations =
    schema.$defs.track.oneOf[5].allOf[1].oneOf;
  if (
    labelRelations.length !== registry.text_keys.length ||
    labelRelations.some(
      (relation, index) =>
        relation.properties.target.const !== registry.text_keys[index] ||
        relation.properties.text_key.const !== registry.text_keys[index]
    )
  ) {
    throw new Error("Scene label relationships do not match the capability registry");
  }
  if (
    schema.properties.required_assets.maxItems !==
      constraints.max_required_assets ||
    schema.properties.tracks.maxItems !== constraints.max_tracks ||
    schema.properties.steps.maxItems !== constraints.max_steps ||
    schema.properties.evidence_refs.maxItems !==
      constraints.max_evidence_refs
  ) {
    throw new Error("Scene collection limits do not match the capability registry");
  }
  const heartAsset =
    schema.allOf[0].then.properties.required_assets.contains.const;
  const circulationAsset =
    schema.allOf[1].then.properties.required_assets.contains.const;
  const flowAssets =
    schema.allOf[2].then.properties.required_assets.allOf.map(
      (condition) => condition.contains.const
    );
  if (
    heartAsset !== constraints.target_assets.heart ||
    circulationAsset !==
      constraints.target_assets["circulation.pulmonary"] ||
    Object.values(constraints.flow_paths).some(
      (requirement) =>
        JSON.stringify(flowAssets) !==
        JSON.stringify(requirement.required_assets)
    )
  ) {
    throw new Error("Scene asset requirements do not match the capability registry");
  }
  assertSameValues(
    "Clip constraint keys",
    Object.keys(constraints.clip_targets),
    registry.clips
  );
  assertSameValues(
    "Morph constraint keys",
    Object.keys(constraints.morph_targets),
    registry.morphs
  );
  assertSameValues(
    "Flow constraint keys",
    Object.keys(constraints.flow_paths),
    registry.paths
  );
  for (const [target, asset] of Object.entries(constraints.target_assets)) {
    if (!registry.targets.includes(target) || !registry.assets.includes(asset)) {
      throw new Error(`Invalid target-to-asset capability mapping for ${target}`);
    }
  }
  for (const [pathName, requirement] of Object.entries(
    constraints.flow_paths
  )) {
    if (
      !registry.targets.includes(requirement.target) ||
      !registry.states.includes(requirement.state) ||
      requirement.required_assets.some(
        (asset) => !registry.assets.includes(asset)
      )
    ) {
      throw new Error(`Invalid flow capability mapping for ${pathName}`);
    }
  }
  for (const target of [
    ...constraints.camera_targets,
    ...constraints.material_targets,
  ]) {
    if (!registry.targets.includes(target)) {
      throw new Error(`Unknown constrained target ${target}`);
    }
  }
  const conflictActions = Object.values(constraints.conflict_groups).flat();
  if (
    new Set(conflictActions).size !== conflictActions.length ||
    conflictActions.some((action) => !registry.actions.includes(action))
  ) {
    throw new Error("Conflict groups contain duplicate or unknown actions");
  }
  assertSameValues(
    "Scene text keys",
    schema.$defs.track.oneOf[5].allOf[1].properties.text_key.enum,
    registry.text_keys
  );
  assertSameValues(
    "Scene fallback modes",
    schema.$defs.fallback.properties.view_mode.enum,
    registry.view_modes
  );
  assertSameValues(
    "Asset manifest ids",
    assetSchema.properties.asset_id.enum,
    registry.assets
  );
  assertSameValues(
    "Asset manifest targets",
    assetSchema.properties.targets.propertyNames.enum,
    registry.targets.filter((target) => !target.startsWith("camera."))
  );
  assertSameValues(
    "Asset manifest clips",
    assetSchema.properties.clips.propertyNames.enum,
    registry.clips
  );
  assertSameValues(
    "Asset manifest morphs",
    assetSchema.properties.morphs.propertyNames.enum,
    registry.morphs
  );
  assertSameValues(
    "Asset manifest paths",
    assetSchema.properties.paths.propertyNames.enum,
    registry.paths
  );
  assertSameValues(
    "Asset manifest material states",
    assetSchema.properties.materials.additionalProperties.items.enum,
    registry.states
  );

  const content = render(registry);
  const stale = [];
  for (const outputPath of outputPaths) {
    if (checkOnly) {
      const current = await readFile(outputPath, "utf8").catch(() => "");
      if (current !== content) {
        stale.push(path.relative(repositoryRoot, outputPath));
      }
      continue;
    }
    await writeFile(outputPath, content, "utf8");
  }

  if (stale.length > 0) {
    throw new Error(
      `Generated scene contract types are stale:\n${stale
        .map((file) => `- ${file}`)
        .join("\n")}`
    );
  }

  process.stdout.write(
    checkOnly
      ? "Scene contract types are current.\n"
      : `Generated scene contract types for ${outputPaths.length} consumers.\n`
  );
}

main().catch((error) => {
  process.stderr.write(
    `${error instanceof Error ? error.message : String(error)}\n`
  );
  process.exitCode = 1;
});
